def mcp_route(raw, headers):
    """Returns (http_status, body_bytes_or_None, extra_headers)."""
    try:
        req = json.loads(raw.decode("utf-8"))
    except Exception:
        return 400, dump_json({"jsonrpc": "2.0", "id": None,
                               "error": {"code": -32700, "message": "Parse error"}}), {}
    if not isinstance(req, dict):
        return 400, dump_json({"jsonrpc": "2.0", "id": None,
                               "error": {"code": -32600, "message": "Invalid Request"}}), {}
    method = req.get("method", "")
    rid = req.get("id")
    params = req.get("params") or {}

    def result(payload, extra=None):
        return 200, dump_json({"jsonrpc": "2.0", "id": rid, "result": payload}), extra or {}

    def error(code, message):
        return 200, dump_json({"jsonrpc": "2.0", "id": rid,
                               "error": {"code": code, "message": message}}), {}

    if method == "server/discover":
        payload = {"supportedVersions": MCP_VERS,
                   "capabilities": {"tools": {}},
                   "serverInfo": MCP_INFO,
                   "_meta": {"io.modelcontextprotocol/serverInfo": MCP_INFO}}
        return result(payload)
    if method == "initialize":
        want = (params.get("protocolVersion") or "")
        chosen = want if want in MCP_VERS else "2025-11-25"
        payload = {"protocolVersion": chosen,
                   "capabilities": {"tools": {}},
                   "serverInfo": MCP_INFO}
        return result(payload, {"Mcp-Session-Id": "session-1"})
    if method in ("notifications/initialized", "notifications/cancelled"):
        return 202, None, {}
    if method == "ping":
        return result({})
    if method == "tools/list":
        return result({"tools": TOOLS})
    if method == "tools/call":
        name = params.get("name", "")
        args = params.get("arguments") or {}
        if name.split("__")[-1] not in TOOL_NAMES and name not in TOOL_NAMES:
            return error(-32602, f"unknown tool {name}")
        obj, is_err, err_text = call_tool(name, args)
        if is_err:
            return result({"content": [{"type": "text",
                                        "text": tool_text({"error": err_text})}],
                           "isError": True})
        return result({"content": [{"type": "text", "text": tool_text(obj)}],
                       "structuredContent": obj})
    return error(-32601, f"method not found: {method}")

