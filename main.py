def rest_route(method, path, query, headers, raw, base_url=""):
    """Returns (status, body_bytes_or_None, extra_headers). Raises ApiError."""
    if method == "GET" and path == "/healthz":
        return 200, b'{"ok":true}', {}
    if not path.startswith("/api/v3"):
        raise ApiError(404, "Not Found")
    # auth: every /api/v3 call needs the shop token
    token = headers.get("authorization", "")
    if TOKEN:
        if token != "Bearer " + TOKEN:
            raise ApiError(401, "Requires authentication")
    sub = path[len("/api/v3"):]
    if sub == "" or sub == "/":
        if method != "GET":
            raise ApiError(404, "Not Found")
        return 200, dump_json({"current_user_url": "/api/v3/user",
                               "repository_url": "/api/v3/repos/{owner}/{repo}",
                               "meta": "/api/v3/meta"}), {"X-OAuth-Scopes": "repo, read:org"}
    if sub == "/meta":
        if method != "GET":
            raise ApiError(404, "Not Found")
        return 200, dump_json({"installed_version": "1.0.0"}), {}
    parts = [unquote(p) for p in sub.strip("/").split("/") if p != ""]
    body = json_body(raw) if method in ("POST", "PUT", "PATCH", "DELETE") else {}
    return rest_top(method, parts, query, body, headers, base_url)


