def ref_list(repo):
    """Sorted [(oid, refname)] for all refs, plus the HEAD pseudo-entry."""
    out = sorted(((oid, name) for name, oid in repo.refs.items()),
                 key=lambda e: e[1])
    head_oid = repo.refs.get("refs/heads/" + repo.default_branch, NIL_OID)
    return head_oid, out


def peel_oid(store, oid):
    got = store.get(oid)
    if got is None:
        return None
    if got[0] == "tag":
        return decode_tag(got[1])["object"]
    return None


def advertise(store, repo, service, proto2):
    """info/refs body for git-upload-pack / git-receive-pack."""
    if proto2:
        if service == "git-upload-pack":
            lines = [b"version 2\n"]
            for k, v in CAPS_V2:
                lines.append(f"{k}={v}\n".encode())
            lines.append(PKT_FLUSH)
            return b"".join(pktline(l) for l in lines[:-1]) + PKT_FLUSH
        head_oid, refs = ref_list(repo)
        body = [pktline(b"# service=git-receive-pack\n"), PKT_FLUSH]
        if not refs:
            body.append(pktline(f"{NIL_OID} capabilities^{{}}\0{CAPS_V0}\n".encode()))
        else:
            first = True
            for oid, name in refs:
                if first:
                    body.append(pktline(f"{oid} {name}\0{CAPS_V0}\n".encode()))
                    first = False
                else:
                    body.append(pktline(f"{oid} {name}\n".encode()))
        body.append(PKT_FLUSH)
        return b"".join(body)
    head_oid, refs = ref_list(repo)
    body = [pktline(f"# service={service}\n".encode()), PKT_FLUSH]
    if service == "git-upload-pack":
        if not refs:
            body.append(pktline(f"{NIL_OID} capabilities^{{}}\0{CAPS_V0}\n".encode()))
        else:
            body.append(pktline(f"{head_oid} HEAD\0{CAPS_V0}\n".encode()))
            for oid, name in refs:
                body.append(pktline(f"{oid} {name}\n".encode()))
                peeled = peel_oid(store, oid)
                if peeled:
                    body.append(pktline(f"{peeled} {name}^{{}}\n".encode()))
    else:
        if not refs:
            body.append(pktline(f"{NIL_OID} capabilities^{{}}\0{CAPS_V0}\n".encode()))
        else:
            first = True
            for oid, name in refs:
                if first:
                    body.append(pktline(f"{oid} {name}\0{CAPS_V0}\n".encode()))
                    first = False
                else:
                    body.append(pktline(f"{oid} {name}\n".encode()))
    body.append(PKT_FLUSH)
    return b"".join(body)


def ls_refs(store, repo, body):
    """v2 ls-refs. Returns the response bytes."""
    packets, _ = scan_pkt(body)
    peel = symrefs = unborn = False
    prefixes = []
    for kind, payload in packets:
        if kind != "data":
            continue
        line = payload.decode("utf-8", "replace").strip()
        if line == "peel":
            peel = True
        elif line == "symrefs":
            symrefs = True
        elif line == "unborn":
            unborn = True
        elif line.startswith("ref-prefix "):
            prefixes.append(line[11:])
    head_oid, refs = ref_list(repo)

    def keep(name):
        return not prefixes or any(name.startswith(p) for p in prefixes)

    out = []
    if keep("HEAD"):
        if head_oid == NIL_OID:
            if unborn:
                line = "unborn HEAD"
                if symrefs:
                    line += " symref-target:refs/heads/" + repo.default_branch
                out.append(line + "\n")
        else:
            line = head_oid + " HEAD"
            if symrefs:
                line += " symref-target:refs/heads/" + repo.default_branch
            out.append(line + "\n")
    for oid, name in refs:
        if not keep(name):
            continue
        line = oid + " " + name
        if peel:
            peeled = peel_oid(store, oid)
            if peeled:
                line += " peeled:" + peeled
        out.append(line + "\n")
    return b"".join(pktline(l.encode()) for l in out) + PKT_FLUSH

def fetch_set(store, wants, haves, depth, old_shallow):
    """Compute (send_oids, shallow, unshallow) for a fetch."""
    _closure_cache = {}

    def tree_closure(tree_oid):
        cached = _closure_cache.get(tree_oid)
        if cached is not None:
            return cached
        seen, stack = set(), [tree_oid]
        while stack:
            oid = stack.pop()
            if oid in seen:
                continue
            got = store.get(oid)
            if got is None:
                continue
            seen.add(oid)
            if got[0] == "tree":
                for _m, _n, child in decode_tree(got[1]):
                    stack.append(child)
        _closure_cache[tree_oid] = seen
        return seen

    def held_for(have):
        """Objects the client already holds through this have. For a full
        fetch that is the have's whole history; for a depth fetch whose
        have is an old shallow boundary, only the have itself plus its
        tree/blobs (a deepen must re-deliver the parent)."""
        got = store.get(have)
        if got is None:
            return set()
        if depth is not None and have in old_shallow and got[0] == "commit":
            out = {have}
            out |= tree_closure(decode_commit(got[1])["tree"])
            return out
        return store.closure([have])

    have_reach = set()
    for h in haves:
        have_reach |= held_for(h)
    if depth is None:
        send = store.closure(wants) - have_reach
        return send, [], []
    # depth-limited walk over commits (deque: no O(n) pop(0))
    included = {}
    boundary = []
    queue = deque((w, 0) for w in wants)
    seen_commit = set()
    while queue:
        oid, level = queue.popleft()
        got = store.get(oid)
        if got is None:
            continue
        if got[0] == "tag":
            queue.append((decode_tag(got[1])["object"], level))
            continue
        if got[0] != "commit":
            continue
        if oid in seen_commit:
            continue
        seen_commit.add(oid)
        included[oid] = level
        c = decode_commit(got[1])
        if level + 1 >= depth:
            boundary.append(oid)
        else:
            for p in c["parents"]:
                queue.append((p, level + 1))
    # closure of included commits: each commit + its tree/blobs only
    # (parents are NOT pulled in: that is the whole point of depth).
    send = set()
    for oid in included:
        send.add(oid)
        c = decode_commit(store.get(oid)[1])
        send |= tree_closure(c["tree"])
    send -= have_reach
    # tags in the send set stay; non-commit wants included directly
    for w in wants:
        got = store.get(w)
        if got is not None and got[0] != "commit":
            send |= store.closure([w])
    send -= have_reach
    shallow, unshallow = [], []
    for oid in boundary:
        c = decode_commit(store.get(oid)[1])
        if any(p not in included for p in c["parents"]):
            shallow.append(oid)
    for old in old_shallow:
        if old in included:
            c = decode_commit(store.get(old)[1])
            if all(p in included for p in c["parents"]):
                if old not in unshallow:
                    unshallow.append(old)
            elif old not in shallow:
                shallow.append(old)
        elif old not in shallow:
            shallow.append(old)
    return send, shallow, unshallow


def sideband(pack):
    out = bytearray()
    for i in range(0, len(pack), 65500):
        chunk = pack[i:i + 65500]
        out += pktline(bytes([1]) + chunk)
    return bytes(out)


def pack_for(store, repo, wants, haves, depth, old_shallow):
    """(pack_bytes_or_None, shallow, unshallow), shared by v2 and v0.
    One build per key: concurrent identical clones wait on one lock."""
    cache_key = (id(repo), tuple(sorted(wants)), tuple(sorted(haves)),
                 depth, tuple(sorted(old_shallow)))
    cached = PACK_CACHE.get(cache_key)
    if cached is not None:
        return cached
    with PACK_LOCK:
        cached = PACK_CACHE.get(cache_key)
        if cached is not None:
            return cached
        send, shallow, unshallow = fetch_set(store, wants, haves, depth, old_shallow)
        if send:
            objs = sorted(send)
            pack = pack_bytes([(oid, store.get(oid)[0], store.get(oid)[1]) for oid in objs])
        else:
            pack = None
        cached = (pack, shallow, unshallow)
        if len(PACK_CACHE) > 64:
            PACK_CACHE.clear()
        PACK_CACHE[cache_key] = cached
        return cached


def parse_fetch(body):
    packets, _ = scan_pkt(body)
    wants, haves, old_shallow = [], [], []
    depth = None
    for kind, payload in packets:
        if kind != "data":
            continue
        line = payload.decode("utf-8", "replace").strip()
        if line.startswith("want "):
            wants.append(line[5:].split()[0])
        elif line.startswith("have "):
            haves.append(line[5:].split()[0])
        elif line.startswith("shallow "):
            old_shallow.append(line[8:].split()[0])
        elif line.startswith("deepen "):
            try:
                depth = int(line[7:])
            except ValueError:
                depth = None
    return wants, haves, depth, old_shallow


def fetch_v2(store, repo, body):
    wants, haves, depth, old_shallow = parse_fetch(body)
    out = bytearray()
    out += pktline(b"acknowledgments\n")
    held = [h for h in haves if store.has(h)]
    if held:
        for h in held:
            out += pktline(f"ACK {h}\n".encode())
        out += pktline(b"ready\n")
    else:
        out += pktline(b"NAK\n")
    out += PKT_DELIM
    pack, shallow, unshallow = pack_for(store, repo, wants, haves, depth, old_shallow)
    if shallow or unshallow:
        out += pktline(b"shallow-info\n")
        for s in shallow:
            out += pktline(f"shallow {s}\n".encode())
        for s in unshallow:
            out += pktline(f"unshallow {s}\n".encode())
        out += PKT_DELIM
    if pack is not None:
        out += pktline(b"packfile\n")
        out += sideband(pack)
    out += PKT_FLUSH
    return bytes(out)


def fetch_v0(store, repo, body):
    wants, haves, depth, old_shallow = parse_fetch(body)
    out = bytearray()
    held = [h for h in haves if store.has(h)]
    if held:
        for h in held:
            out += pktline(f"ACK {h}\n".encode())
    else:
        out += pktline(b"NAK\n")
    pack, shallow, unshallow = pack_for(store, repo, wants, haves, depth, old_shallow)
    for s in shallow:
        out += pktline(f"shallow {s}\n".encode())
    for s in unshallow:
        out += pktline(f"unshallow {s}\n".encode())
    if pack is not None:
        out += sideband(pack)
    out += PKT_FLUSH
    return bytes(out)


def receive_pack(store, repo, body):
    """Parse push commands + pack; apply fast-forward-only ref updates.
    Returns the sideband report bytes."""
    packets, rest = scan_pkt(body)
    commands = []
    for kind, payload in packets:
        if kind != "data":
            continue
        line = payload.decode("utf-8", "replace")
        nul = line.find("\0")
        if nul >= 0:
            line = line[:nul]
        line = line.strip()
        if not line:
            continue
        parts = line.split(" ")
        if len(parts) >= 3:
            commands.append((parts[0], parts[1], parts[2]))
    out = bytearray()
    report = []
    if rest:
        try:
            objs = unpack_pack(rest)
        except Exception as exc:
            report.append(f"unpack {exc}\n")
            out += pktline(b"\x01" + pktline(f"unpack {exc}\n".encode()))
            out += PKT_FLUSH
            return bytes(out)
        for oid, otype, data in objs:
            store.put(otype, data)
    for old, new, ref in commands:
        with DB.mutex:  # store here is the ObjDb; lock lives on DB
            cur = repo.refs.get(ref)
            if new == NIL_OID:  # delete
                if cur is None:
                    report.append(f"ng {ref} remote ref does not exist\n")
                else:
                    del repo.refs[ref]
                    report.append(f"ok {ref}\n")
            elif old == NIL_OID:  # create
                if cur is not None:
                    report.append(f"ng {ref} reference already exists\n")
                elif not store.has(new):
                    report.append(f"ng {ref} object not found\n")
                else:
                    repo.refs[ref] = new
                    report.append(f"ok {ref}\n")
            else:  # update: must be fast-forward
                if cur is None:
                    report.append(f"ng {ref} remote ref does not exist\n")
                elif cur != old:
                    report.append(f"ng {ref} non-fast-forward\n")
                elif not store.has(new):
                    report.append(f"ng {ref} object not found\n")
                elif not store.is_anc(old, new):
                    report.append(f"ng {ref} non-fast-forward\n")
                else:
                    repo.refs[ref] = new
                    report.append(f"ok {ref}\n")
    out += pktline(b"\x01" + pktline(b"unpack ok\n"))
    for line in report:
        out += pktline(b"\x01" + pktline(line.encode()))
    out += PKT_FLUSH
    return bytes(out)

