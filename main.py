def cur_enc(pos):
    return b64e(f"c:{pos}")


def cur_dec(cursor):
    if not cursor:
        return -1
    try:
        text = b64d(cursor)
        if text and text.startswith("c:"):
            return int(text[2:])
    except Exception:
        return -1
    return -1


def connect(items, args, kind="IssueConnection"):
    first = args.get("first")
    after = cur_dec(args.get("after"))
    start = after + 1
    page = items[start:start + first] if isinstance(first, int) else items[start:]
    end_cursor = cur_enc(start + len(page) - 1) if page else None
    edge_kind = kind.replace("Connection", "Edge")
    return {"__type": kind, "nodes": page,
            "edges": [{"__type": edge_kind, "node": it,
                       "cursor": cur_enc(start + k)}
                      for k, it in enumerate(page)],
            "pageInfo": {"__type": "PageInfo",
                         "hasNextPage": start + len(page) < len(items),
                         "hasPreviousPage": start > 0,
                         "startCursor": cur_enc(start) if page else None,
                         "endCursor": end_cursor},
            "totalCount": len(items)}


def issue_nodes(repo, args):
    # snapshot once: issues only grow, but a concurrent mutation must not
    # change the list mid-sort
    items = list(repo.issues.values())
    states = args.get("states")
    if states:
        wanted = {s.lower() for s in states}
        items = [i for i in items if i["state"] in wanted]
    order = args.get("orderBy") or {}
    direction = (order.get("direction") or "ASC").upper()
    # issues are created in number order == creation order; sorting by
    # number is the same as by createdAt, and cheaper than parsing dates
    items.sort(key=lambda i: i["number"], reverse=(direction == "DESC"))
    return [issue_node(repo, i) for i in items]


