def page_of(items, query, base_url):
    """Slice items per ?per_page=&page=; returns (page_items, link_header)."""
    try:
        per_page = int(query.get("per_page", ["30"])[0])
    except ValueError:
        per_page = 30
    try:
        page = int(query.get("page", ["1"])[0])
    except ValueError:
        page = 1
    per_page = max(1, min(per_page, 100))
    page = max(1, page)
    start = (page - 1) * per_page
    chunk = items[start:start + per_page]
    total_pages = max(1, (len(items) + per_page - 1) // per_page)
    links = []
    if page < total_pages:
        links.append(f'<{base_url}?per_page={per_page}&page={page + 1}>; rel="next"')
        links.append(f'<{base_url}?per_page={per_page}&page={total_pages}>; rel="last"')
    if page > 1:
        links.append(f'<{base_url}?per_page={per_page}&page={page - 1}>; rel="prev"')
        links.append(f'<{base_url}?per_page={per_page}&page=1>; rel="first"')
    return chunk, ", ".join(links)


