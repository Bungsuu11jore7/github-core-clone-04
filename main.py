GIT_RE = re.compile(r"^/([^/]+)/([^/]+?)(?:\.git)?/(info/refs|git-upload-pack|git-receive-pack)$")


def dispatch(method, path, query, headers, raw):
    """Returns (status, body_bytes_or_None, content_type, extra_headers).
    Raises ApiError for JSON error replies."""
    # GraphQL
    if path == "/api/graphql":
        if method != "POST":
            raise ApiError(404, "Not Found")
        if TOKEN and headers.get("authorization") != "Bearer " + TOKEN:
            raise ApiError(401, "Requires authentication")
        try:
            payload = json.loads(raw.decode("utf-8"))
        except Exception:
            return 400, dump_json({"errors": [{"message": "request body must be valid JSON"}]}), "application/json", {}
        if isinstance(payload, list):
            out = [gql_run(item.get("query", ""), item.get("variables") or {})
                   for item in payload]
            return 200, dump_json(out), "application/json", {}
        return 200, dump_json(gql_run(payload.get("query", ""),
                                      payload.get("variables") or {})), "application/json", {}
    # MCP
    if path == "/mcp":
        if method == "DELETE":
            return 204, None, "application/json", {}
        if method != "POST":
            raise ApiError(404, "Not Found")
        if TOKEN and headers.get("authorization") != "Bearer " + TOKEN:
            raise ApiError(401, "Requires authentication")
        status, body, extra = mcp_route(raw, headers)
        return status, body, "application/json", extra
    # git smart HTTP: /<owner>/<repo>.git/<service>
    m = GIT_RE.match(path)
    if m:
        owner, repo_name, service = m.group(1), m.group(2), m.group(3)
        repo = DB.find_repo(owner, repo_name)
        if repo is None:
            raise ApiError(404, "Not Found")
        if service == "info/refs":
            svc = query.get("service", [None])[0]
            if svc not in ("git-upload-pack", "git-receive-pack"):
                raise ApiError(400, "service is required")
            proto2 = headers.get("git-protocol") == "version=2"
            body = advertise(DB.objects, repo, svc, proto2)
            return 200, body, f"application/x-{svc}-advertisement", {}
        if service == "git-upload-pack":
            packets, _ = scan_pkt(raw)
            is_ls = any(k == "data" and p.decode("utf-8", "replace").startswith("command=ls-refs")
                        for k, p in packets)
            if is_ls:
                body = ls_refs(DB.objects, repo, raw)
            elif headers.get("git-protocol") == "version=2":
                body = fetch_v2(DB.objects, repo, raw)
            else:
                body = fetch_v0(DB.objects, repo, raw)
            return 200, body, "application/x-git-upload-pack-result", {}
        body = receive_pack(DB.objects, repo, raw)
        return 200, body, "application/x-git-receive-pack-result", {}
    # REST v3 + healthz
    base_url = "http://" + headers.get("host", "127.0.0.1")
    status, body, extra = rest_route(method, path, query, headers, raw, base_url)
    return status, body, "application/json", extra


# ---------------------------------------------------------------- HTTP server
# Minimal HTTP/1.1 server on raw sockets: one listener thread, one daemon
# thread per connection, buffered reads, one sendall per reply.
# No Date header, no Server header, keep-alive by default.
REASONS = {200: "OK", 201: "Created", 202: "Accepted", 204: "No Content",
           400: "Bad Request", 401: "Unauthorized", 404: "Not Found",
           405: "Method Not Allowed", 409: "Conflict", 422: "Unprocessable Entity",
           500: "Internal Server Error"}


def read_chunked(buf, conn):
    """Decode a chunked body; buf holds bytes already read. Returns
    (body, rest_of_buffer)."""
    body = bytearray()
    while True:
        while b"\r\n" not in buf:
            chunk = conn.recv(65536)
            if not chunk:
                return bytes(body), buf
            buf += chunk
        line, buf = buf.split(b"\r\n", 1)
        try:
            size = int(line.split(b";", 1)[0].strip(), 16)
        except ValueError:
            return bytes(body), buf
        if size == 0:
            # trailing headers until blank line
            while b"\r\n\r\n" not in buf:
                chunk = conn.recv(65536)
                if not chunk:
                    return bytes(body), buf
                buf += chunk
            _trail, buf = buf.split(b"\r\n\r\n", 1)
            return bytes(body), buf
        while len(buf) < size + 2:
            chunk = conn.recv(65536)
            if not chunk:
                return bytes(body), buf
            buf += chunk
        body += buf[:size]
        buf = buf[size + 2:]
    return bytes(body), buf


def serve_conn(conn):
    buf = b""
    try:
        conn.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        while True:
            while b"\r\n\r\n" not in buf:
                chunk = conn.recv(65536)
                if not chunk:
                    return
                buf += chunk
            head, buf = buf.split(b"\r\n\r\n", 1)
            lines = head.split(b"\r\n")
            try:
                method, target, _ver = lines[0].split(b" ", 2)
            except ValueError:
                return
            method = method.decode("latin-1")
            target = target.decode("latin-1")
            headers = {}
            for ln in lines[1:]:
                k, _, v = ln.partition(b":")
                headers[k.strip().lower().decode("latin-1")] = v.strip().decode("latin-1")
            if headers.get("transfer-encoding", "").lower() == "chunked":
                raw, buf = read_chunked(buf, conn)
            else:
                try:
                    n = int(headers.get("content-length") or 0)
                except ValueError:
                    n = 0
                while len(buf) < n:
                    chunk = conn.recv(65536)
                    if not chunk:
                        return
                    buf += chunk
                raw, buf = buf[:n], buf[n:]
            parsed = urlparse(target)
            path = parsed.path
            query = parse_qs(parsed.query)
            try:
                status, body, ctype, extra = dispatch(method, path, query, headers, raw)
            except ApiError as exc:
                status, body, ctype, extra = exc.status, dump_json({"message": exc.message}), "application/json", {}
            except Exception as exc:
                sys.stderr.write(f"handler error: {exc!r}\n")
                status, body, ctype, extra = 500, dump_json({"message": "Internal Server Error"}), "application/json", {}
            if body is None:
                body = b""
            head_out = ("HTTP/1.1 %d %s\r\nContent-Type: %s\r\nContent-Length: %d\r\n"
                        "X-GitHub-Request-Id: %s\r\n"
                        % (status, REASONS.get(status, "OK"), ctype, len(body), req_id()))
            for k, v in extra.items():
                head_out += f"{k}: {v}\r\n"
            head_out += "\r\n"
            try:
                conn.sendall(head_out.encode("latin-1") + body)
            except (BrokenPipeError, ConnectionResetError):
                return
            if headers.get("connection", "").lower() == "close":
                return
    except (ConnectionResetError, BrokenPipeError, OSError):
        return
    finally:
        try:
            conn.close()
        except Exception:
            pass


class Server:
    def __init__(self, host, port):
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.sock.bind((host, port))
        self.sock.listen(256)
        self.port = self.sock.getsockname()[1]
        self.stopping = False

    def serve(self):
        # One daemon thread per connection, no pool cap: the suite's client
        # opens many connections at once (50 concurrent clones), and a
        # bounded pool lets threads blocked in recv on idle keep-alive
        # connections starve new ones until the client closes them (~4 s).
        while not self.stopping:
            try:
                conn, _addr = self.sock.accept()
            except OSError:
                return
            threading.Thread(target=serve_conn, args=(conn,),
                             daemon=True).start()

    def shutdown(self):
        self.stopping = True
        try:
            self.sock.close()
        except Exception:
            pass


# ---------------------------------------------------------------- lifecycle
def http_json(url, payload, timeout=10):
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(url, data=data,
                                 headers={"Content-Type": "application/json"},
                                 method="POST" if data is not None else "GET")
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def main():
    env_url = os.environ.get("MAKEFUN_ENV_URL")
    if not env_url:
        sys.stderr.write("MAKEFUN_ENV_URL is not set\n")
        return 1
    server = Server("127.0.0.1", 0)
    port = server.port
    threading.Thread(target=server.serve, daemon=True).start()
    base = env_url.rstrip("/")
    delay = 0.1
    for _ in range(60):
        try:
            http_json(base + "/register", {"port": port}, timeout=5)
            break
        except Exception:
            time.sleep(delay)
            delay = min(delay * 1.5, 2.0)
    else:
        sys.stderr.write("register failed\n")
        return 1
    while True:
        try:
            done = http_json(base + "/done", None, timeout=5)
            if done.get("done"):
                break
        except Exception:
            pass
        time.sleep(0.5)
    server.shutdown()
    return 0


