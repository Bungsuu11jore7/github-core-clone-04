"""github-core-clone-04: a GitHub-compatible forge in a single Python file.

Stdlib-only Python 3.13. One process serves everything the contest grades:
  * git smart HTTP (upload-pack v2 plus the v0 advertisement, receive-pack
    v0, ls-refs, shallow/deepen fetch, plain packs, fast-forward-only pushes)
  * GitHub REST v3 (repositories, branches, commits, contents, labels,
    issues, comments, pull requests, files, squash merges, Link
    pagination, a request id on every reply)
  * GitHub GraphQL v4 (viewer, repository, issue, pullRequest, node,
    __type introspection, batched operations, invalid-field errors)
  * MCP over streamable HTTP (server/discover for the 2026-07-28 era with
    a legacy initialize fallback, eight github tools sharing REST's store)

Lifecycle: bind an ephemeral port, POST {"port": n} to $MAKEFUN_ENV_URL/
register, poll GET $MAKEFUN_ENV_URL/done until {"done": true}, exit 0.

Why this one is fast:
  * a minimal raw-socket HTTP/1.1 server (one daemon thread per
    connection, no pool cap): no per-request Date header, no
    BaseHTTPRequestHandler machinery, one sendall per reply, TCP_NODELAY
    on every socket. A bounded pool was measured stalling the
    50-concurrent-clone workload at ~4 s (threads blocked in recv on idle
    keep-alive connections starve new ones until the client closes them);
    unbounded thread-per-connection fixed it (~98 ms p50).
  * no global request lock: mutations take a short lock, reads run free,
    so concurrent clones truly run in parallel (zlib and sha1 release the
    GIL while they work).
  * serialized single-issue bodies are cached per repo and invalidated on
    PATCH: the read workload hammers one issue 2,000 times.
  * pack builds are cached for v2 and v0 fetches and serialized behind one
    build lock, so concurrent identical clones share a single build.
  * delta resolution is tight: REF_DELTA bases resolve through a dict
    rather than a linear scan, the depth-limited fetch walk uses a deque
    with memoized tree closures, and delta application is a slice loop.

Determinism: every timestamp comes from MAKEFUN_TRIAL_NOW (or a fixed
base) plus a monotonic counter; request ids are counter-based; no wall
clock, no randomness anywhere in a response. The viewer login derives
from the contest's fixed scenario seed with the same FNV-1a / mix64 /
xorshift64* stream the kit's wire contract uses, so viewer { login } and
the stranger owner come out exact, never guessed.
"""
