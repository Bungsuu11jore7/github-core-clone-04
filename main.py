def repo_sub(method, owner, name, rest, query, body):
    repo = need_repo(owner, name)
    if rest == ["branches"]:
        if method != "GET":
            raise ApiError(404, "Not Found")
        with DB.mutex:
            ref_items = sorted(repo.refs.items())
        out = [{"name": ref[len("refs/heads/"):], "commit": {"sha": oid}}
               for ref, oid in ref_items
               if ref.startswith("refs/heads/")]
        return 200, dump_json(out), {}
    if rest == ["commits"]:
        if method != "GET":
            raise ApiError(404, "Not Found")
        sha = query.get("sha", [None])[0]
        tip = DB.resolve(repo, sha) if sha else DB.head_oid(repo)
        if tip is None:
            return 200, b"[]", {}
        got = DB.objects.get(tip)
        if got is None:
            raise ApiError(404, f"No commit found for SHA: {sha}")
        if got[0] == "tag":
            tip = decode_tag(got[1])["object"]
        chain = DB.objects.chain(tip)
        out = []
        for oid in reversed(chain):
            c = decode_commit(DB.objects.get(oid)[1])
            out.append({"sha": oid, "commit": {"message": c["message"].rstrip("\n"),
                        "tree": {"sha": c["tree"]}},
                        "parents": [{"sha": p} for p in c["parents"]]})
        return 200, dump_json(out), {}
    if rest == ["git", "refs"]:
        if method != "POST":
            raise ApiError(404, "Not Found")
        ref = body.get("ref", "")
        sha = body.get("sha", "")
        if not ref.startswith("refs/") or not DB.objects.get(sha):
            raise ApiError(422, "Invalid ref or sha")
        with DB.mutex:
            if ref in repo.refs:
                raise ApiError(422, "Reference already exists")
            repo.refs[ref] = sha
        return 201, dump_json({"ref": ref, "object": {"sha": sha, "type": "commit"}}), {}
    if rest[0] == "contents":
        return contents(method, repo, rest[1:], query, body)
    if rest == ["labels"]:
        if method != "POST":
            raise ApiError(404, "Not Found")
        lname = body.get("name")
        if not lname:
            raise ApiError(422, "name is required")
        with DB.mutex:
            if lname in repo.labels:
                raise ApiError(422, "Label already exists")
            repo.labels[lname] = body.get("color", "ffffff")
        return 201, dump_json({"name": lname, "color": repo.labels[lname]}), {}
    if rest[0] == "issues":
        return issues(method, repo, rest[1:], query, body)
    if rest[0] == "pulls":
        return pulls(method, repo, rest[1:], query, body)
    raise ApiError(404, "Not Found")

def contents(method, repo, rest, query, body):
    fpath = "/".join(rest)
    ref = query.get("ref", [None])[0]
    tip = DB.resolve(repo, ref) if ref else DB.head_oid(repo)
    if method == "GET":
        if tip is None:
            raise ApiError(404, "Not Found")
        got = DB.objects.get(tip)
        if got is None:
            raise ApiError(404, "Not Found")
        if got[0] == "tag":
            tip = decode_tag(got[1])["object"]
        tree_oid = decode_commit(DB.objects.get(tip)[1])["tree"]
        files = flatten_tree(DB.objects, tree_oid)
        if not fpath:
            entries = dir_list(repo, files, "")
            return 200, dump_json(entries), {}
        if fpath in files:
            oid, _mode = files[fpath]
            data = DB.objects.get(oid)[1]
            return 200, dump_json({"type": "file", "encoding": "base64", "size": len(data),
                                   "name": fpath.split("/")[-1], "path": fpath, "sha": oid,
                                   "content": base64.b64encode(data).decode()}), {}
        entries = dir_list(repo, files, fpath)
        if entries is None:
            raise ApiError(404, "Not Found")
        return 200, dump_json(entries), {}
    if method == "PUT":
        message = body.get("message", "")
        content_b64 = body.get("content", "")
        try:
            data = base64.b64decode(content_b64, validate=False)
        except Exception:
            raise ApiError(422, "content must be base64")
        branch = body.get("branch") or repo.default_branch
        refname = "refs/heads/" + branch
        with DB.mutex:
            cur_tip = repo.refs.get(refname)
            if cur_tip is None and repo.refs:
                raise ApiError(422, f"No commit found for branch {branch}")
            files = {}
            parents = []
            if cur_tip is not None:
                got = DB.objects.get(cur_tip)
                if got is None:
                    raise ApiError(422, f"No commit found for branch {branch}")
                files = flatten_tree(DB.objects, decode_commit(got[1])["tree"])
                parents = [cur_tip]
            existed = fpath in files
            if existed:
                if "sha" in body and body["sha"] != files[fpath][0]:
                    raise ApiError(409, "sha does not match")
            blob_oid = DB.add_blob(data)
            files[fpath] = (blob_oid, "100644")
            tree_oid = tree_of_files(DB.objects, files)
            ts = DB.tick()
            author = f"{SELF_NAME} <{SELF_EMAIL}>"
            cdata = encode_commit(tree_oid, parents, message, author, author, ts)
            commit_oid = DB.objects.put("commit", cdata)
            repo.refs[refname] = commit_oid
        status = 200 if existed else 201
        return status, dump_json({"content": {"name": fpath.split("/")[-1], "path": fpath,
                                              "sha": blob_oid, "size": len(data),
                                              "encoding": "base64"},
                                  "commit": {"sha": commit_oid, "message": message}}), {}
    if method == "DELETE":
        message = body.get("message", "")
        branch = body.get("branch") or repo.default_branch
        refname = "refs/heads/" + branch
        with DB.mutex:
            cur_tip = repo.refs.get(refname)
            if cur_tip is None:
                raise ApiError(404, "Not Found")
            files = flatten_tree(DB.objects, decode_commit(DB.objects.get(cur_tip)[1])["tree"])
            if fpath not in files:
                raise ApiError(404, "Not Found")
            if "sha" in body and body["sha"] != files[fpath][0]:
                raise ApiError(409, "sha does not match")
            del files[fpath]
            tree_oid = tree_of_files(DB.objects, files)
            ts = DB.tick()
            author = f"{SELF_NAME} <{SELF_EMAIL}>"
            cdata = encode_commit(tree_oid, [cur_tip], message, author, author, ts)
            commit_oid = DB.objects.put("commit", cdata)
            repo.refs[refname] = commit_oid
        return 200, dump_json({"commit": {"sha": commit_oid, "message": message}}), {}
    raise ApiError(404, "Not Found")


def dir_list(repo, files, prefix):
    """Entries directly under prefix ('' = root). None if prefix is not a dir."""
    entries, seen = {}, False
    for path, (oid, _mode) in files.items():
        if prefix and not path.startswith(prefix + "/"):
            continue
        rel = path[len(prefix) + 1:] if prefix else path
        head, _, _tail = rel.partition("/")
        if head == "":
            continue
        seen = True
        if _tail:
            entries[head] = {"type": "dir", "name": head,
                             "path": (prefix + "/" + head) if prefix else head,
                             "sha": None}
        else:
            entries[head] = {"type": "file", "name": head, "path": path,
                             "sha": oid, "size": len(DB.objects.get(oid)[1])}
    if not seen and prefix:
        return None
    return [entries[k] for k in sorted(entries)]

