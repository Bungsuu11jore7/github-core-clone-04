def resolve_val(v, variables):
    if isinstance(v, dict):
        if "var" in v:
            return variables.get(v["var"])
        if "enum" in v:
            return v["enum"]
        return {k: resolve_val(x, variables) for k, x in v.items()}
    if isinstance(v, list):
        return [resolve_val(x, variables) for x in v]
    return v


