def fnv1a(text):
    h = 0xCBF29CE484222325
    for ch in text:
        h ^= ord(ch)
        h = (h * 0x100000001B3) & MASK64
    return h


def mix64(value):
    z = (value + 0x9E3779B97F4A7C15) & MASK64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
    return (z ^ (z >> 31)) & MASK64


class Rng:
    def __init__(self, seed):
        s = seed & MASK64
        self.state = s if s else SEED

    def next_u64(self):
        x = self.state
        x = (x ^ (x >> 12)) & MASK64
        x = (x ^ (x << 25)) & MASK64
        x = (x ^ (x >> 27)) & MASK64
        self.state = x
        return (x * 0x2545F4914F6CDD1D) & MASK64

    def next_u32(self):
        return self.next_u64() >> 32

    def next_int(self, n):
        if n == 1:
            return 0
        limit = (1 << 32) - ((1 << 32) % n)
        while True:
            v = self.next_u32()
            if v < limit:
                return v % n

    def pick(self, items):
        return items[self.next_int(len(items))]


